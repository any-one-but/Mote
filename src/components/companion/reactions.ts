export type Reaction = {
  id: string;
  group: ReactionGroup;
  name: string;
  /** The stimulus: what Mote notices. */
  when: string;
  /** The outcome: what Mote does. */
  then: string;
  /** How it moves Mote's feelings, each time it fires. */
  effects?: Effects;
  /** "live" is built; "idea" is planned and doesn't happen yet. */
  status: "live" | "idea";
};

